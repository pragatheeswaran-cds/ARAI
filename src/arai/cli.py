"""Command line for every step, with project-relative paths (final-spec component 15).

Offline:  generate -> validate -> train -> dry-run -> ablation -> stress -> select -> test -> publish
Serving:  db-migrate -> serve (API, optionally with the worker) / worker / register
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

from arai import contract
from arai.generator import generate_world, write_world
from arai.generator.world import _code_sha256 as generator_code_sha256
from arai.validation import validate_world


def _generate(args) -> int:
    for seed in args.seed:
        owner = contract.retired_seed_owner(seed)
        if owner:
            print(f"Seed {seed} belongs to {owner}. Its world is the record of that experiment and is never generated under "
                  "the current contract; check out that experiment's commit to reproduce it.")
            return 1
        started = time.time()
        world = generate_world(seed, args.customers, abuse_enabled=not args.no_abuse)
        existing = _existing_generator(world, args.artifact_root)
        current = {"config_sha256": world.context.s.config_sha256(), "code_sha256": generator_code_sha256()}
        if existing and existing != current and not args.overwrite:
            print(f"{world.world_id} already exists and was generated by a different simulator or contract. It is the record of "
                  "an earlier experiment and is left untouched; use a seed of the current contract, or --overwrite to replace it.")
            return 1
        out = write_world(world, args.artifact_root, args.private_root)
        report = validate_world(out["operational"])
        print(f"{world.world_id}: {world.n_customers} customers, {world.summary['sales_order']} orders, "
              f"{world.summary['return_order_line']} return lines in {time.time() - started:.1f}s -> {out['operational']}")
        if not report.accepted:
            print(json.dumps(report.to_dict(), indent=2))
            return 1
    return 0


def _existing_generator(world, artifact_root) -> dict | None:
    """The simulator hashes of a world already on disk under this identifier, if there is one."""
    from arai import paths
    name = world.world_id + ("" if world.abuse_enabled else ".abuse-off")
    manifest = Path(artifact_root or paths.ARTIFACT_ROOT) / "worlds" / name / "operational" / "manifest.json"
    if not manifest.is_file():
        return None
    generator = json.loads(manifest.read_text(encoding="utf-8"))["generator"]
    return {key: generator[key] for key in ("config_sha256", "code_sha256")}


def _validate(args) -> int:
    report = validate_world(args.directory)
    print(json.dumps(report.to_dict(), indent=2))
    return 0 if report.accepted else 1


def _card(card) -> str:
    columns = ["role", "status", "k", "true_positives", "precision", "recall", *(s + "_fpr" for s in contract.segments()), "reasons"]
    return card[columns].round(4).to_string()


def _train(args) -> int:
    from arai import experiment
    result = experiment.train(args.experiment)
    for record in result["candidates"] + result["references"]:
        print(f"{record['candidate_id']}: {record['status']} in {record['duration_seconds']}s ({record['reference_kind']})")
    return 0


def _dry_run(args) -> int:
    from arai import experiment
    result = experiment.dry_run(args.experiment, levers_changed=args.lever or (), record_ref=args.record)
    print(_card(result["card"]))
    print(json.dumps(result["calibration"], indent=1))
    return 0


def _select(args) -> int:
    from arai import experiment
    result = experiment.validate(args.experiment)
    print(_card(result["card"]))
    print("selection:", result["selection_status"], result["selected_model_id"])
    return 0


def _test(args) -> int:
    from arai import experiment
    result = experiment.final_test(args.experiment)
    print(_card(result["card"]))
    print("final test:", result["final_test_status"])
    return 0 if result["final_test_status"] == "passed" else 2


def _ablation(args) -> int:
    from arai import ablation
    result = ablation.run(args.experiment, args.candidate)
    print(f"{result['candidate_id']}, {result['measured_on']}; return-rate rule {result['baseline_precision']:.3f}")
    for row in result["variants"]:
        print(f"  {row['variant']:<40} precision {row['precision']:.3f}")
    for row in result["honest_groups"]["groups"]:
        print(f"  {row['label']:<66} reviewed by model {row['model_rate']:.3f}, by rule {row['rule_rate']:.3f}")
    return 0


def _stress(args) -> int:
    from arai import experiment
    for world in experiment.stress(args.experiment)["worlds"]:
        best = max((r for r in world["rankings"] if r["role"] == "candidate"), key=lambda r: r["precision"])
        rule = next(r for r in world["rankings"] if r["role"] == "baseline")
        print(f"{world['world_id']} {world['mechanism']:<36} rule {rule['precision']:.3f}  best candidate {best['ranking']} "
              f"{best['precision']:.3f} ({best['status']})")
    return 0


def _publish(args) -> int:
    from arai import publishing
    result = publishing.publish(args.experiment, demo_world=args.demo_world)
    print(json.dumps({k: result[k] for k in ("pointer", "baseline_id", "model_id", "report")}, indent=1))
    return 0


def _service(args):
    from arai.service.config import from_env
    return from_env()


def _db_migrate(args) -> int:
    from arai.service.store import Store
    applied = Store(_service(args).database_url).migrate()
    print("applied:", applied or "nothing new")
    return 0


def _serve(args) -> int:
    import uvicorn

    from arai.service.api import create_app
    uvicorn.run(create_app(_service(args), with_worker=args.with_worker), host=args.host, port=args.port, log_level="info")
    return 0


def _local(args) -> int:
    """One command for a local rehearsal: an embedded PostgreSQL, the API, the worker and the built UI."""
    import logging

    import uvicorn

    from arai import paths
    from arai.service.api import create_app
    from arai.service.config import ServiceConfig
    try:
        import pgserver
    except ImportError:
        print("The embedded PostgreSQL is a development dependency: run `uv sync` (or use docker compose).")
        return 1
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s %(message)s")
    server = pgserver.get_server(args.pg_dir or paths.POSTGRES_DIR)
    static = paths.REPO_ROOT / "web" / "dist"
    if not (static / "index.html").is_file():
        print("web/dist is missing: run `npm install` and `npm run build` in web/ to serve the UI; starting the API only.")
        static = None
    config = ServiceConfig(database_url=server.get_uri(), artifact_root=paths.ARTIFACT_ROOT)
    print(f"ARAI local rehearsal on http://{args.host}:{args.port}  (database in {server.pgdata})")
    uvicorn.run(create_app(config, with_worker=True, static_dir=static), host=args.host, port=args.port, log_level="info")
    return 0


def _baseline_rehearsal(args) -> int:
    """A second local instance that serves the return-rate rule only: the demo's cold open (docs/demo-script.md, 1d).

    Its fixture lives in git under rehearsal/baseline/artifacts: the baseline bundle, the published report rewritten as
    if no candidate had passed the gate, and the active pointer. Its runtime state (the embedded database and the
    registered snapshot) sits beside it and is ignored by git. It runs beside `arai local` without sharing anything.
    The fixture is rebuilt from the current artifacts when it is missing, names a bundle that is not there, or --fresh
    is given. On first start the demo world is registered and scored with the rule.
    """
    import logging
    import shutil
    import threading
    import time

    import httpx
    import uvicorn

    from arai import bundles, paths
    from arai.operational import TABLES
    from arai.service.api import create_app
    from arai.service.config import ServiceConfig
    try:
        import pgserver
    except ImportError:
        print("The embedded PostgreSQL is a development dependency: run `uv sync`.")
        return 1
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s %(message)s")
    work = paths.REPO_ROOT / "rehearsal" / "baseline"
    root = work / "artifacts"
    if args.fresh:
        for state in (work / "postgres", root / "datasets", root / "bundles", root / "experiments", root / "active"):
            shutil.rmtree(state, ignore_errors=True)
    pointer = bundles.read_active(root)
    if pointer is None or not (root / "bundles" / str(pointer.get("baseline_id"))).is_dir():
        for stale in (root / "bundles", root / "experiments", root / "active"):
            shutil.rmtree(stale, ignore_errors=True)
        for bundle in sorted((paths.ARTIFACT_ROOT / "bundles").iterdir()):
            if bundle.name.startswith("b-"):                               # the rule's bundle only; the model stays out
                shutil.copytree(bundle, root / "bundles" / bundle.name)
        source = next((paths.ARTIFACT_ROOT / "experiments").glob("*/published/experiment.json"))
        report = json.loads(source.read_text(encoding="utf-8"))
        report["summary"].update(selection_status="no_selected_model", selected_model_id=None, selected_candidate_id=None,
                                 final_test_status="not_run")
        published = root / "experiments" / report["summary"]["experiment_id"] / "published"
        published.mkdir(parents=True, exist_ok=True)
        (published / "experiment.json").write_text(json.dumps(report), encoding="utf-8")
        baseline_id = next(p.name for p in sorted((root / "bundles").iterdir()) if p.name.startswith("b-"))
        bundles.activate(None, baseline_id, "no_selected_model", report["summary"]["experiment_id"],
                         "Baseline rehearsal: the return-rate rule is served as if no candidate had passed the gate.", root)
    server = pgserver.get_server(work / "postgres")
    static = paths.REPO_ROOT / "web" / "dist"
    if not (static / "index.html").is_file():
        print("web/dist is missing: run `npm install` and `npm run build` in web/ to serve the UI; starting the API only.")
        static = None
    config = ServiceConfig(database_url=server.get_uri(), artifact_root=root)
    base = f"http://{args.host}:{args.port}"

    def seed():
        """Once the API answers: register and score the demo world with the rule, unless a run already succeeded here."""
        with httpx.Client(timeout=300) as client:
            for _ in range(240):
                try:
                    if client.get(base + "/api/v1/health").status_code == 200:
                        break
                except httpx.HTTPError:
                    pass
                time.sleep(0.5)
            else:
                return
            if any(r["status"] == "succeeded" for r in client.get(base + "/api/v1/runs").json()["items"]):
                print(f"baseline rehearsal: {args.demo_world} is already scored here; open {base}")
                return
            world = paths.ARTIFACT_ROOT / "worlds" / args.demo_world / "operational"
            files = {name: (f"{name}.csv", (world / f"{name}.csv").read_bytes(), "text/csv") for name in TABLES}
            dataset = client.post(base + "/api/v1/datasets", data={"manifest": (world / "manifest.json").read_text(encoding="utf-8")},
                                  files=files).json()
            run = client.post(base + "/api/v1/runs", json={"dataset_id": dataset["dataset_id"],
                                                           "idempotency_key": f"baseline-rehearsal-{dataset['dataset_id']}"}).json()
            print(f"baseline rehearsal: scoring {args.demo_world} with the return-rate rule, run {run.get('run_id')}; open {base}")

    threading.Thread(target=seed, daemon=True).start()
    print(f"ARAI baseline rehearsal (return-rate rule only) on {base}  (fixture in {root}, database in {server.pgdata}); "
          "run `arai local` on another port")
    uvicorn.run(create_app(config, with_worker=True, static_dir=static), host=args.host, port=args.port, log_level="info")
    return 0


def _worker(args) -> int:
    import logging

    from arai.service import worker
    from arai.service.store import Store
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s %(message)s")
    config = _service(args)
    store = Store(config.database_url)
    store.migrate()
    worker.reconcile(config, store)
    worker.run_forever(config, store)
    return 0


def _register(args) -> int:
    """Register a world directory through the same validation and storage path the upload route uses."""
    from arai.operational import TABLES
    from arai.service import datasets
    from arai.service.store import Store
    config = _service(args)
    store = Store(config.database_url)
    store.migrate()
    args.directory = Path(args.directory)
    files = {name: (args.directory / f"{name}.csv").read_bytes() for name in TABLES}
    try:
        row, created = datasets.register(store, config.artifact_root, (args.directory / "manifest.json").read_text(encoding="utf-8"), files)
    except datasets.Rejected as rejected:
        print(json.dumps(rejected.report.to_dict() if rejected.report else {"message": rejected.message}, indent=2))
        return 1
    print(f"{row['id']}: world {row['world_id']}, {row['customer_count']} customers ({'registered' if created else 'already registered'})")
    return 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="arai", description="ARAI: synthetic worlds, training, evaluation and serving")
    commands = parser.add_subparsers(dest="command", required=True)
    generate = commands.add_parser("generate", help="generate, write and validate one or more worlds")
    generate.add_argument("--seed", type=int, nargs="+", required=True, help="world seeds from contracts/experiment.yaml")
    generate.add_argument("--customers", type=int, default=None, help="override the world size (default: by seed purpose)")
    generate.add_argument("--no-abuse", action="store_true", help="base shopping and honest returns only (diagnostic)")
    generate.add_argument("--artifact-root", type=Path, default=None)
    generate.add_argument("--private-root", type=Path, default=None)
    generate.add_argument("--overwrite", action="store_true", help="replace a world that another simulator or contract generated")
    generate.set_defaults(run=_generate)
    validate = commands.add_parser("validate", help="validate an operational world directory; nonzero exit on rejection")
    validate.add_argument("directory", type=Path)
    validate.set_defaults(run=_validate)

    for name, handler, text in (
            ("train", _train, "freeze training features and fit the candidates and references (training worlds only)"),
            ("dry-run", _dry_run, "gate dry run and calibration check on out-of-fold training scores; selects nothing"),
            ("select", _select, "score the validation worlds, apply the gate and freeze the selection"),
            ("test", _test, "evaluate the frozen selection once on the test worlds")):
        command = commands.add_parser(name, help=text)
        command.add_argument("--experiment", default=contract.experiment_id())
        command.set_defaults(run=handler)
        if name == "dry-run":
            command.add_argument("--lever", action="append", help="a difficulty lever that was changed (repeatable); disclosed in reports")
            command.add_argument("--record", default=None, help="path of the dated calibration record, disclosed in reports")
    ablation = commands.add_parser("ablation", help="what the result depends on: feature-family ablations and honest-group review "
                                                    "rates, out of fold on training worlds")
    ablation.add_argument("--experiment", default=contract.experiment_id())
    ablation.add_argument("--candidate", default=None, help="default: the selected candidate, else the best of the dry run")
    ablation.set_defaults(run=_ablation)
    stress = commands.add_parser("stress", help="the frozen estimators on the stress worlds; diagnostic, selects nothing")
    stress.add_argument("--experiment", default=contract.experiment_id())
    stress.set_defaults(run=_stress)
    publish = commands.add_parser("publish", help="build bundles, set the active pointer and write the published experiment report")
    publish.add_argument("--experiment", default=contract.experiment_id())
    publish.add_argument("--demo-world", default=None, help="export this world's synthetic truth for the evaluation page")
    publish.set_defaults(run=_publish)

    commands.add_parser("db-migrate", help="apply database migrations (DATABASE_URL)").set_defaults(run=_db_migrate)
    serve = commands.add_parser("serve", help="run the API (DATABASE_URL, ARTIFACT_ROOT, APP_PROFILE, UI_ORIGINS)")
    serve.add_argument("--host", default="127.0.0.1")
    serve.add_argument("--port", type=int, default=8000)
    serve.add_argument("--with-worker", action="store_true", help="also run the single scoring worker in this process")
    serve.set_defaults(run=_serve)
    commands.add_parser("worker", help="run the single scoring worker").set_defaults(run=_worker)
    local = commands.add_parser("local", help="local rehearsal: embedded PostgreSQL + API + worker + built UI, one process")
    local.add_argument("--host", default="127.0.0.1")
    local.add_argument("--port", type=int, default=8000)
    local.add_argument("--pg-dir", type=Path, default=None, help="PostgreSQL data directory (default: postgres/ in the contract's data folder)")
    local.set_defaults(run=_local)
    rehearsal = commands.add_parser("baseline-rehearsal", help="a second local instance serving the return-rate rule only (the demo's "
                                                             "cold open): its fixture in rehearsal/baseline, its database beside it, "
                                                             "the demo world scored on first start")
    rehearsal.add_argument("--host", default="127.0.0.1")
    rehearsal.add_argument("--port", type=int, default=8011)
    rehearsal.add_argument("--demo-world", default="W5401")
    rehearsal.add_argument("--fresh", action="store_true", help="rebuild the fixture from the current bundles and start with an empty database")
    rehearsal.set_defaults(run=_baseline_rehearsal)
    register = commands.add_parser("register", help="validate and register an operational world directory as a dataset")
    register.add_argument("directory", type=Path)
    register.set_defaults(run=_register)
    args = parser.parse_args(argv)
    return args.run(args)


if __name__ == "__main__":
    sys.exit(main())
